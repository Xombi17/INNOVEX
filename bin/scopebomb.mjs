#!/usr/bin/env node
import { resolve } from "node:path";
import { scanDirectory } from "../packages/engine/cli.ts";

const args = process.argv.slice(2);

if (args.includes("-h") || args.includes("--help") || args.length === 0) {
  process.stdout.write(`
\x1b[1m\x1b[36mScopeBomb CLI — Non-Human Identity Firewall & CI/CD Pipeline Gate\x1b[0m

\x1b[1mUsage:\x1b[0m
  scopebomb scan [directory] [options]

\x1b[1mOptions:\x1b[0m
  --json                 Output full AuditReport as frozen JSON
  --markdown             Generate formatted Markdown report (ideal for PR comments)
  --fail-on-risk <score> Exit with code 1 if risk score >= score (e.g. 70)
  -v, --version          Show ScopeBomb CLI version
  -h, --help             Show this help message

\x1b[1mExamples:\x1b[0m
  scopebomb scan .
  scopebomb scan ./services/ai-agent --fail-on-risk 75
  scopebomb scan . --markdown > pr-security-report.md
`);
  process.exit(0);
}

if (args.includes("-v") || args.includes("--version")) {
  process.stdout.write("scopebomb-cli v1.2.0\n");
  process.exit(0);
}

const command = args[0];
if (command !== "scan") {
  process.stderr.write(`Unknown command "${command}". Run "scopebomb --help" for available commands.\n`);
  process.exit(1);
}

const targetDir = args[1] && !args[1].startsWith("-") ? args[1] : ".";
const isJson = args.includes("--json");
const isMarkdown = args.includes("--markdown");
const riskThresholdIdx = args.indexOf("--fail-on-risk");
const failThreshold = riskThresholdIdx !== -1 && args[riskThresholdIdx + 1] ? parseInt(args[riskThresholdIdx + 1], 10) : null;

try {
  const targetPath = resolve(targetDir);
  const report = scanDirectory(targetPath);

  if (isJson) {
    process.stdout.write(JSON.stringify(report, null, 2) + "\n");
  } else if (isMarkdown) {
    const md = [
      `## 💣 ScopeBomb Non-Human Identity Audit Report`,
      `**Target:** \`${targetDir}\` | **Max Risk Score:** \`${report.summary.max_risk_score}/100\` | **Status:** ${report.summary.max_risk_score >= (failThreshold ?? 80) ? "❌ **FAIL**" : "✔ **PASS**"}`,
      ``,
      `### 🔍 Audit Findings`,
      `- **Credential Findings:** ${report.shadow_secrets.length} token(s) across ${new Set(report.shadow_secrets.map(f => f.source_file)).size} configuration file(s).`,
      `- **Trust Boundaries Breached:** ${report.summary.trust_boundary_crossings.join(", ") || "None"}.`,
      `- **Max Cascade Depth:** ${report.summary.max_hops} hop(s).`,
      ``,
      `### 🛡️ Required Surgical Containment Steps`,
      ...report.full_containment.ordered_steps.map(s => `- **[P${s.priority}] ${s.issuer}:** ${s.action_type} on \`${s.target_resource}\` (${s.command_or_endpoint})`),
      ``,
      `*Generated by [ScopeBomb CI/CD Gate](https://scopebomb.vercel.app)*`,
    ].join("\n");
    process.stdout.write(md + "\n");
  } else {
    // High-craft colorized terminal output
    process.stdout.write("\n\x1b[1m\x1b[36m⚡ ScopeBomb Non-Human Identity Audit\x1b[0m\n");
    process.stdout.write(`Target: \x1b[33m${targetPath}\x1b[0m\n`);
    process.stdout.write(`Findings: \x1b[1m${report.shadow_secrets.length}\x1b[0m token(s) identified\n`);
    process.stdout.write(`Trust Boundaries: \x1b[35m${report.summary.trust_boundary_crossings.join(" ➔ ") || "None"}\x1b[0m\n`);
    process.stdout.write(`Max Risk Score: \x1b[1m${report.summary.max_risk_score >= 70 ? "\x1b[31m" : "\x1b[32m"}${report.summary.max_risk_score}/100\x1b[0m\n`);
    process.stdout.write(`Headline: ${report.summary.headline}\n\n`);

    process.stdout.write("\x1b[1mSurgical Containment Plan:\x1b[0m\n");
    for (const step of report.full_containment.ordered_steps) {
      process.stdout.write(`  \x1b[36m[P${step.priority}]\x1b[0m \x1b[1m${step.issuer}\x1b[0m: ${step.action_type} (Target: ${step.target_resource})\n`);
    }
    process.stdout.write("\n");
  }

  if (failThreshold !== null && report.summary.max_risk_score >= failThreshold) {
    process.stderr.write(`\x1b[1m\x1b[31m[CI GATE BLOCKED]\x1b[0m Maximum risk score (${report.summary.max_risk_score}/100) meets or exceeds threshold (${failThreshold}). Merge rejected.\n`);
    process.exit(1);
  }
} catch (err) {
  process.stderr.write(`ScopeBomb error: ${err instanceof Error ? err.message : String(err)}\n`);
  process.exit(1);
}
